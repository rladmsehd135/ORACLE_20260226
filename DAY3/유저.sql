CREATE TABLE TBL_USER (
    USERID      VARCHAR2(20)   NOT NULL,
    PWD         VARCHAR2(100)  NOT NULL,
    USERNAME    VARCHAR2(20)   NOT NULL,
    BIRTH       DATE           NOT NULL,
    PHONE       VARCHAR2(20)   NOT NULL,
    GENDER      CHAR(1),
    EMAIL       VARCHAR2(30),
    RECOMMID    VARCHAR2(20),
    CDATETIME   DATE           NOT NULL,
    
    CONSTRAINT PK_TBL_USER PRIMARY KEY (USERID)
);


CREATE TABLE TBL_BOARD (
    BOARDNO     NUMBER         NOT NULL,
    USERID      VARCHAR2(20)   NOT NULL,
    TITLE       VARCHAR2(100)  NOT NULL,
    CONTENTS    VARCHAR2(300),
    CNT         NUMBER         NOT NULL,
    KIND        CHAR(1)        NOT NULL,
    CDATETIME   DATE           NOT NULL,
    UDATETIME   DATE           NOT NULL,
    
    CONSTRAINT PK_TBL_BOARD PRIMARY KEY (BOARDNO)
);

CREATE SEQUENCE BOARD_SEQ
START WITH 1
INCREMENT BY 1;

CREATE TABLE TBL_COMMENT (
    COMMENTNO     NUMBER         NOT NULL,
    BOARDNO       NUMBER,
    USERID        VARCHAR2(20),
    CONTENTS       VARCHAR2(300),
    P_COMMENTNO   NUMBER,
    CDATETIME     DATE           NOT NULL,
    UDATETIME     DATE           NOT NULL,
    
    CONSTRAINT PK_TBL_COMMENT PRIMARY KEY (COMMENTNO)
);

CREATE SEQUENCE COMMENT_SEQ
START WITH 1
INCREMENT BY 1;

