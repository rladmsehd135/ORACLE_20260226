-- 게시글 제목, 내용, 조회수 ,작성자 이름 출력
SELECT TITLE, CONTENTS , CNT, USERNAME
FROM TBL_BOARD B
INNER JOIN TBL_USER U ON B.USERID = U.USERID;

--사용자 아이디 , 이름 , 해당 사용자가 작성한 댓글 개수 출력
SELECT U.USERID, USERNAME ,댓글개수
FROM TBL_USER U
INNER JOIN (
    SELECT USERID, COUNT(*) AS 댓글개수
    FROM TBL_COMMENT
    GROUP BY USERID
) T ON U.USERID = T.USERID;


--작성한 게시글의 조회수 합이 가장 많은 상위 3명의 이름과 조회수 합 출력
SELECT USERNAME, SUM_CNT
FROM(
    SELECT USERID, SUM(CNT) AS SUM_CNT
    FROM TBL_BOARD
    GROUP BY USERID
    ORDER BY SUM_CNT DESC
) T
INNER JOIN TBL_USER U ON T.USERID = U.USERID
WHERE ROWNUM <= 3;

SELECT 제목, 댓글개수
FROM(
    SELECT TITLE AS 제목,COUNT(*) AS 댓글개수,1 AS ORDERKEY
    FROM TBL_BOARD TB
    INNER JOIN TBL_COMMENT TC ON TB.BOARDNO = TC.BOARDNO
    GROUP BY TB.BOARDNO, TITLE
    UNION
    SELECT '댓글전체개수',COUNT(*),2 AS ORDERKEY
    FROM TBL_COMMENT
    ORDER BY ORDERKEY, 댓글개수 DESC
);



