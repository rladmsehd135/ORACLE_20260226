--내가 속한 부서의 평균 급여보다 높은 급여를 받는 사람의 사번,이름,급여,부서이름
--속한 부서의 평균급여 출력
SELECT P.NAME,
       D2.DNAME,
       P.PAY,
       T.AVG_PAY
FROM PROFESSOR P
INNER JOIN DEPARTMENT D1
    ON P.DEPTNO = D1.DEPTNO
INNER JOIN DEPARTMENT D2
    ON D1.PART = D2.DEPTNO
INNER JOIN (
    SELECT D2.DEPTNO,
           AVG(P.PAY) AS AVG_PAY
    FROM PROFESSOR P
    INNER JOIN DEPARTMENT D1
        ON P.DEPTNO = D1.DEPTNO
    INNER JOIN DEPARTMENT D2
        ON D1.PART = D2.DEPTNO
    GROUP BY D2.DEPTNO
) T
    ON D2.DEPTNO = T.DEPTNO
WHERE P.PAY > T.AVG_PAY;
