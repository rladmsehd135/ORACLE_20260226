SELECT EMPNO,ENAME,SAL, MAX_SAL
FROM EMP E
INNER JOIN(
SELECT DEPTNO ,MAX(SAL) MAX_SAL
FROM EMP E
GROUP BY DEPTNO
) T ON E.DEPTNO = T.DEPTNO AND MAX_SAL = SAL;

