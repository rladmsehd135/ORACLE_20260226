SELECT STU_DEPT,
       COUNT(*) AS 학생수
FROM STUDENT
GROUP BY STU_DEPT
HAVING COUNT(*) = (
        SELECT MAX(CNT)
        FROM (
            SELECT COUNT(*) CNT
            FROM STUDENT
            GROUP BY STU_DEPT
        )
)OR COUNT(*) = (
        SELECT MIN(CNT)
        FROM (
            SELECT COUNT(*) CNT
            FROM STUDENT
            GROUP BY STU_DEPT
        )
);
