-- 1. ALLEN과 같은 JOB, DEPTNO(부서)를 가진 사람을 구하시오.(ENAME, DNAME 출력)
SELECT * FROM EMP;
SELECT * FROM SALGRADE;
SELECT * FROM DEPT;

SELECT DNAME, ENAME
FROM EMP E
INNER JOIN DEPT D ON E.DEPTNO = D.DEPTNO
WHERE JOB = 'SALESMAN' AND E.DEPTNO = D.DEPTNO;
-- 2. 자신의 부서 급여등급 평균보다 높은 등급인 사람의 이름, 부서명, 급여등급을 구하시오.
SELECT E1.ENAME,
       D.DNAME,
       S1.GRADE
FROM EMP E1
INNER JOIN DEPT D 
    ON E1.DEPTNO = D.DEPTNO
INNER JOIN SALGRADE S1 
    ON E1.SAL BETWEEN S1.LOSAL AND S1.HISAL
WHERE S1.GRADE > (
    SELECT AVG(S2.GRADE)
    FROM EMP E2
    INNER JOIN SALGRADE S2
        ON E2.SAL BETWEEN S2.LOSAL AND S2.HISAL
    WHERE E2.DEPTNO = E1.DEPTNO
);

-- STUDENT, ENROL, SUBJECT
-- 1. 컴퓨터정보과의 평균보다 평균이 낮은 학과의 학과명, 점수 출력
SELECT STU_DEPT,
       AVG(ENR_GRADE) AS 평균점수
FROM STUDENT S
INNER JOIN ENROL E
    ON S.STU_NO = E.STU_NO
GROUP BY STU_DEPT
HAVING AVG(ENR_GRADE) < (
    SELECT AVG(E2.ENR_GRADE)
    FROM STUDENT S2
    INNER JOIN ENROL E2
        ON S2.STU_NO = E2.STU_NO
    WHERE S2.STU_DEPT = '컴퓨터정보'
);

