-- 5. 학생들의 전체 평균 키보다 큰 키를 가진 학생들의 학번, 이름, 키를 출력하시오.
SELECT STU_NO, STU_NAME, STU_HEIGHT
FROM STUDENT
WHERE STU_HEIGHT > (SELECT AVG(STU_HEIGHT)
FROM STUDENT);

-- 6. 본인 학과의 평균 키보다 큰 학생들의 이름, 학과, 키, 학과 평균키 값 출력
SELECT S.STU_NAME,
       S.STU_DEPT,
       S.STU_HEIGHT
FROM STUDENT S
WHERE S.STU_HEIGHT > (
    SELECT AVG(STU_HEIGHT)
    FROM STUDENT
    WHERE STU_DEPT = S.STU_DEPT
);
-- EMP, SALGRADE, DEPT
-- 1. 급여 등급이 3이상인 사원의 사번, 이름, 급여등급을 출력하시오.
SELECT EMPNO,ENAME,S.GRADE
FROM EMP E
INNER JOIN SALGRADE S ON E.SAL BETWEEN S.LOSAL AND S.HISAL
WHERE S.GRADE >= 3;
-- 2. 사번, 이름, 팀장(MGR)의 이름을 출력하시오.
SELECT E1.EMPNO,E1.ENAME,E2.ENAME AS MGR
FROM EMP E1
INNER JOIN EMP E2 ON E1.EMPNO = E2.MGR;

-- 3. 부서별 가장 높은 급여를 받는 사원의 사번, 이름, 급여, 부서명을 출력하시오.
SELECT E.EMPNO,E.ENAME, E.SAL,D.DNAME
FROM EMP E
INNER JOIN DEPT D 
    ON E.DEPTNO = D.DEPTNO
WHERE E.SAL = (
    SELECT MAX(SAL)
    FROM EMP
    WHERE DEPTNO = E.DEPTNO
);

