--날짜별 수익
SELECT DY,SP
FROM(   
    SELECT
    TO_CHAR(ORDERDATE, 'YYYY-MM-DD') AS DY ,SUM(SALEPRICE) AS SP,1 AS ORDERKEY
    FROM ORDERS
    GROUP BY ORDERDATE
    UNION
    SELECT
        '매출총액',SUM(SALEPRICE),2 AS ORDERKEY
        FROM ORDERS
    ORDER BY ORDERKEY , SP DESC
);

--책 가격이 가장 높은 상위 3개의 책이름, 가격 출력
SELECT ROWNUM , B.*
FROM(
    SELECT BOOKNAME,PRICE
    FROM BOOK B
    GROUP BY BOOKNAME,PRICE
    ORDER BY PRICE DESC
) B
WHERE ROWNUM <= 3;


