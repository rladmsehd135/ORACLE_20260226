--날짜별 매출 
--날짜 ,해달 날짜의 ㅐ출, 매출이 20000이상일 경우 '상'
--10000이상일 경우 '중'  , 그외는 '하'로 표기
SELECT ORDERDATE,SUM(SALEPRICE),
    CASE
        WHEN SUM(SALEPRICE) > 20000 THEN '상'
        WHEN SUM(SALEPRICE) > 1000 THEN '중'
        ELSE '하'
    END 매출정보
FROM ORDERS
GROUP BY ORDERDATE;



