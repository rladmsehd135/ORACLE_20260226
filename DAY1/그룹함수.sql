SELECT POSITION, MAX(PAY)
FROM PROFESSOR
GROUP BY POSITION;

--그룹함수에서 조건
SELECT STU_DEPT, COUNT(*)
FROM STUDENT
GROUP BY STU_DEPT
HAVING COUNT(*) >= 4;

SELECT * FROM PROFESSOR;
-- 각 직급(POSITION)별 급여 평균 300 이상
--직급 ,평균 급여 출력
SELECT POSITION, ROUND(AVG(PAY), 1)
FROM PROFESSOR
GROUP BY POSITION
HAVING AVG(PAY) >=300;


